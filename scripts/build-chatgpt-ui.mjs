/**
 * [INPUT]: ui 源码、官方 MCP Apps SDK、Lucide 与锁定构建依赖
 * [OUTPUT]: 单文件 results.html；可显式导出到指定网关目录，check 仅核对字节
 * [POS]: 组件构建边界，不部署、不修改账户或发起业务调用
 * [PROTOCOL]: 变更时更新此头部，然后检查 AGENTS.md
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { values } = parseArgs({ options: { output: { type: "string" }, check: { type: "boolean" } } });
const result = await build({ entryPoints: [resolve(root, "ui/app.mjs")], bundle: true, write: false, platform: "browser", format: "iife", target: "es2022", minify: true, legalComments: "none" });
const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const css = readFileSync(resolve(root, "ui/styles.css"), "utf8");
const html = `<!doctype html>\n<!-- Generated by beatapi-agent-plugin/scripts/build-chatgpt-ui.mjs; do not edit. -->\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BeatAPI results</title><style>${css}</style></head><body><main id="app" aria-live="polite"></main><script>${js}</script></body></html>\n`;
const output = resolve(values.output ?? resolve(root, "dist/chatgpt-ui/results.html"));
if (values.check) {
  if (readFileSync(output, "utf8") !== html) throw new Error("ChatGPT UI bundle is stale; rebuild from its owning source.");
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, html);
}
console.log(`${values.check ? "Verified" : "Built"} ChatGPT UI: ${output}`);
